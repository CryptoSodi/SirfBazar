const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const ts = require(path.join(root, 'apps/web/node_modules/typescript'));
const React = require(path.join(root, 'apps/web/node_modules/react'));
const { renderToStaticMarkup } = require(path.join(root, 'apps/web/node_modules/react-dom/server'));
const lucide = require(path.join(root, 'apps/web/node_modules/lucide-react'));
function load(relative) {
  const moduleObject = { exports: {} };
  const source = fs.readFileSync(path.join(root, relative), 'utf8');
  const output = ts.transpileModule(source, { compilerOptions: {
    module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, jsx: ts.JsxEmit.ReactJSX,
  }}).outputText;
  vm.runInNewContext(output, { module: moduleObject, exports: moduleObject.exports, require: name => {
    if (name === 'lucide-react') return lucide;
    if (name === 'react/jsx-runtime') return require(path.join(root, 'apps/web/node_modules/react/jsx-runtime'));
    throw Error('Unexpected import: ' + name);
  }});
  return { exports: moduleObject.exports, source };
}
for (const file of ['web/components/AppIcon.tsx', 'pos/src/components/AppIcon.tsx', 'admin/src/components/AppIcon.tsx', 'shop/src/components/ReferenceIcon.tsx']) {
  test(file + ': every alias renders a named-library SVG with accessible defaults', () => {
    const { exports: component, source } = load('apps/' + file);
    const Icon = component.AppIcon || component.ReferenceIcon;
    const names = [...source.matchAll(/^  (\w+): \w+,/gm)].map(match => match[1]);
    assert.ok(names.length > 60);
    for (const name of names) {
      const html = renderToStaticMarkup(React.createElement(Icon, { name }));
      assert.match(html, /^<svg/);
      assert.match(html, /class="[^"]*lucide/);
      assert.match(html, /aria-hidden="true"/);
      assert.match(html, /focusable="false"/);
      assert.match(html, /stroke="currentColor"/);
    }
    if (component.ReferenceIcon) {
      const html = renderToStaticMarkup(React.createElement(Icon, { name: 'pin', label: 'Shop location' }));
      assert.match(html, /aria-label="Shop location"/);
      assert.doesNotMatch(html, /aria-hidden="true"/);
    }
  });
}
test('web and native aliases use the same library glyph for every meaning', () => {
  const files = ['web/components/AppIcon.tsx', 'merchant-app/components/AppIcon.tsx', 'customer-app/components/AppIcon.tsx', 'rider-app/components/AppIcon.tsx', 'shop/src/components/ReferenceIcon.tsx'];
  const maps = files.map(file => [...fs.readFileSync(path.join(root, 'apps', file), 'utf8').matchAll(/^  (\w+): (\w+),/gm)].map(m => [m[1],m[2]]));
  for (const map of maps.slice(1)) assert.deepEqual(map, maps[0]);
});
test('category selection accepts only allowlisted icons and handles old data', () => {
  const { categoryIconName } = load('apps/shared/category-icons.ts').exports;
  assert.equal(categoryIconName('fruits-vegetables', 'legacy-emoji'), 'carrot');
  assert.equal(categoryIconName('unknown', 'lucide:milk'), 'milk');
  assert.equal(categoryIconName('unknown', 'lucide:__proto__'), 'grid');
  assert.equal(categoryIconName(), 'grid');
});
test('standalone category adapters stay in sync with the canonical mapping', () => {
  const expected = '// Generated by scripts/sync-category-icons.cjs. Do not edit by hand.\n' +
    fs.readFileSync(path.join(root, 'apps/shared/category-icons.ts'), 'utf8');
  for (const file of ['apps/web/lib/category-icons.ts', 'apps/admin/src/lib/category-icons.ts', 'apps/customer-app/lib/category-icons.ts']) {
    assert.equal(fs.readFileSync(path.join(root, file), 'utf8'), expected);
  }
});
