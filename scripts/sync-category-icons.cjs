// Keep standalone app builds independent of sibling-directory resolver settings.
// Edit apps/shared/category-icons.ts, then run this script and test-icon-system.cjs.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const source = '// Generated by scripts/sync-category-icons.cjs. Do not edit by hand.\n' +
  fs.readFileSync(path.join(root, 'apps/shared/category-icons.ts'), 'utf8');
for (const file of ['apps/web/lib/category-icons.ts', 'apps/admin/src/lib/category-icons.ts', 'apps/customer-app/lib/category-icons.ts']) {
  fs.writeFileSync(path.join(root, file), source);
}
