require('reflect-metadata');
const { test, after } = require('node:test');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const bcrypt = require('bcryptjs');
require('./disposable-database.cjs').disposableUrl();
const { PrismaService } = require('../src/prisma/prisma.service.ts');
const { JwtService } = require('@nestjs/jwt');
const { AuthService } = require('../src/auth/auth.service.ts');
const { JwtAuthGuard } = require('../src/common/guards/jwt-auth.guard.ts');
const { CatalogService } = require('../src/catalog/catalog.service.ts');
const { CartService } = require('../src/cart/cart.service.ts');
const { AccessService } = require('../src/common/access.service.ts');
const { PricingService } = require('../src/common/pricing.service.ts');
const { CouponsService } = require('../src/coupons/coupons.service.ts');
const { RefundsService } = require('../src/refunds/refunds.service.ts');
const { OrdersService } = require('../src/orders/orders.service.ts');
const { OrderStatusService } = require('../src/orders/order-status.service.ts');
const { MerchantOrdersService } = require('../src/orders/merchant-orders.service.ts');
const { RiderService } = require('../src/rider/rider.service.ts');
const { SettlementsService } = require('../src/settlements/settlements.service.ts');
const { RealtimeGateway } = require('../src/realtime/realtime.gateway.ts');
const { provisionReviewAccounts, disableReviewAccounts } = require('../src/auth/review-accounts-admin.ts');
const r = require('../src/auth/review-access.ts');
const db = new PrismaService();
after(() => db.$disconnect());

test('PostgreSQL review lifecycle: real auth, isolated inventory/order/delivery, limits and revocation', async () => {
  process.env.NODE_ENV = 'production';
  process.env.OTP_PROVIDER = 'whatsapp';
  process.env.PLAY_REVIEW_ENABLED = 'true';
  process.env.PLAY_REVIEW_EXPIRES_AT = new Date(Date.now() + 86400000).toISOString();
  process.env.JWT_SECRET = 'disposable-review-only';
  const codes = ['681293', '725194', '839215'];
  for (const [index, account] of r.REVIEW_ACCOUNTS.entries()) process.env[`PLAY_REVIEW_${account.context.toUpperCase()}_CODE_HASH`] = await bcrypt.hash(codes[index], 12);
  const suffix = randomUUID();
  const category = await db.category.create({ data: { name: 'Review test category', slug: `review-test-${suffix}` } });
  const product = await db.product.create({ data: { name: 'Review test product', slug: `review-test-${suffix}`, categoryId: category.id } });
  const owner = await db.user.create({ data: { role: 'MERCHANT_OWNER' } });
  const shop = await db.merchant.create({ data: { userId: owner.id, shopName: 'Ordinary fixture', shopType: 'GROCERY', phoneNumber: '+923008889999', address: 'Fixture', city: 'Lahore', latitude: 31.5826, longitude: 74.3276, approvalStatus: 'APPROVED', isOnline: true, isOpen: true, openingTime: '00:00', closingTime: '23:59' } });
  const normalListing = await db.merchantProduct.create({ data: { merchantId: shop.id, productId: product.id, stockQuantity: 50, pricePaisa: 10000 } });
  const normalUser = await db.user.create({ data: { role: 'CUSTOMER', customer: { create: {} } }, include: { customer: true } });
  await provisionReviewAccounts(db);
  const demoListing = await db.merchantProduct.findFirstOrThrow({ where: { merchantId: r.REVIEW_SHOP_ID } });
  const jwt = new JwtService({ secret: 'disposable-review-only', signOptions: { expiresIn: '15m' } });
  let externalOtpSends = 0;
  const auth = new AuthService(db, jwt, { sendOtp: async () => { externalOtpSends++; } }, {});
  const tokens = [];
  for (const [index, account] of r.REVIEW_ACCOUNTS.entries()) {
    await auth.sendOtp(account.phone);
    await assert.rejects(auth.sendOtp(account.phone), /wait/);
    await assert.rejects(auth.verifyOtp(account.phone, '123456', undefined, account.context), /invalid/);
    tokens.push(await auth.verifyOtp(account.phone, codes[index], undefined, account.context));
    await assert.rejects(auth.verifyOtp(account.phone, codes[index], undefined, account.context), /No pending/);
  }
  assert.equal(externalOtpSends, 0);
  const [customer, merchant, rider] = r.REVIEW_ACCOUNTS;
  await assert.rejects(auth.verifyOtp(merchant.phone, codes[1], undefined, 'customer'), /for this app/);
  await auth.sendOtp('+923009998888');
  assert.equal(externalOtpSends, 1);
  const guard = new JwtAuthGuard(jwt, { getAllAndOverride: () => false }, db);
  async function guarded(token, controller = 'OrdersController', handler = 'list') {
    const request = { headers: { authorization: `Bearer ${token}` } };
    return guard.canActivate({ switchToHttp: () => ({ getRequest: () => request }), getClass: () => ({ name: controller }), getHandler: () => ({ name: handler }) });
  }
  assert.equal(await guarded(tokens[0].accessToken), true);
  await assert.rejects(guarded(tokens[0].accessToken, 'AuthController', 'googleLink'), /not available/);
  await assert.rejects(guarded(tokens[1].accessToken, 'MerchantController', 'createStaff'), /not available/);
  const catalog = new CatalogService(db);
  assert.deepEqual((await catalog.nearbyMerchants({}, customer.userId)).items.map(m => m.id), [r.REVIEW_SHOP_ID]);
  assert.ok(!(await catalog.nearbyMerchants({})).items.some(m => m.id === r.REVIEW_SHOP_ID));
  await assert.rejects(catalog.merchantProducts(r.REVIEW_SHOP_ID, {}), /not found/);
  assert.ok((await catalog.nearbyProducts({}, customer.userId)).items.every(p => p.merchant.id === r.REVIEW_SHOP_ID));
  assert.ok((await catalog.productDetail(demoListing.productId, {})).offers.every(p => p.merchant.id !== r.REVIEW_SHOP_ID));

  const realtime = { emitToOrder() {}, emitToMerchant() {}, emitToRider() {}, emitToUser() {}, emitToAdmins() {} };
  const notifications = { async notify() {}, async notifyMany() {} };
  const access = new AccessService(db), pricing = new PricingService(), coupons = new CouponsService(db);
  const baskets = new CartService(db, coupons, pricing);
  const demoOwner = { customerId: r.REVIEW_CUSTOMER_ID };
  await assert.rejects(baskets.addItem(demoOwner, normalListing.id, 1), /isolated/);
  await assert.rejects(baskets.addItem({ customerId: normalUser.customer.id }, demoListing.id, 1), /isolated/);
  const guest = await db.guestSession.create({ data: { sessionToken: randomUUID(), expiresAt: new Date(Date.now() + 86400000) } });
  await assert.rejects(baskets.addItem({ guestSessionId: guest.id }, demoListing.id, 1), /isolated/);
  await baskets.addItem({ guestSessionId: guest.id }, normalListing.id, 1);
  await assert.rejects(baskets.mergeGuestCart(guest.sessionToken, customer.userId), /isolated/);
  const cart = await baskets.addItem(demoOwner, demoListing.id, 1);
  const status = new OrderStatusService(db, realtime);
  const orders = new OrdersService(db, baskets, coupons, new RefundsService(db, notifications), notifications, realtime, access, pricing, status);
  const checkout = { requestId: randomUUID(), cartId: cart.id, deliveryAddressId: 'play-review-v1-address', paymentMethod: 'COD' };
  await assert.rejects(orders.quoteOrder(customer.userId, { ...checkout, couponCode: 'REAL-PROMOTION' }), /Coupons/);
  const quote = await orders.quoteOrder(customer.userId, checkout);
  const order = await orders.placeOrder(customer.userId, { ...checkout, approvedQuote: quote.approvedQuote });
  const dispatch = new MerchantOrdersService(db, access, notifications, realtime, orders, status);
  const delivery = new RiderService(db, access, notifications, realtime, status);
  await dispatch.accept(merchant.userId, order.id);
  await dispatch.markReady(merchant.userId, order.id);
  await dispatch.assignRider(merchant.userId, order.id, r.REVIEW_RIDER_ID);
  await delivery.arrivedAtShop(rider.userId, order.id, {});
  await delivery.pickedUp(rider.userId, order.id, {});
  const deliveryOrder = await db.order.findUniqueOrThrow({ where: { id: order.id } });
  await delivery.delivered(rider.userId, order.id, { otp: deliveryOrder.deliveryOtp, note: 'Isolated review fixture; no real cash or delivery.' });
  assert.equal((await db.order.findUniqueOrThrow({ where: { id: order.id } })).status, 'DELIVERED');
  assert.equal((await db.merchantProduct.findUniqueOrThrow({ where: { id: normalListing.id } })).stockQuantity, 50);
  const settlement = new SettlementsService(db, notifications);
  await assert.rejects(settlement.generate(owner.id, { merchantId: r.REVIEW_SHOP_ID, startDate: '2020-01-01', endDate: '2099-01-01' }), /cannot be settled/);
  const stock = (await db.merchantProduct.findUniqueOrThrow({ where: { id: demoListing.id } })).stockQuantity;
  await provisionReviewAccounts(db);
  assert.equal((await db.merchantProduct.findUniqueOrThrow({ where: { id: demoListing.id } })).stockQuantity, stock);

  await db.otpCode.updateMany({ where: { phoneNumber: customer.phone }, data: { attempts: 20, createdAt: new Date(Date.now() - 120000), consumedAt: null, expiresAt: new Date(Date.now() + 300000) } });
  await auth.sendOtp(customer.phone);
  await assert.rejects(auth.verifyOtp(customer.phone, codes[0]), /limit reached/);
  const disabled = await disableReviewAccounts(db);
  assert.ok(disabled.revokedSessions >= 3);
  await assert.rejects(guarded(tokens[0].accessToken), /Authentication required/);
  await assert.rejects(auth.refreshTokens(tokens[0].refreshToken), /Invalid refresh/);
  await assert.rejects(auth.sendOtp(customer.phone), /unavailable/);
  const gateway = new RealtimeGateway(jwt, db);
  let disconnected = false;
  assert.equal(await gateway.current({ data: { userId: customer.userId, role: 'CUSTOMER', sessionId: jwt.decode(tokens[0].accessToken).sid }, disconnect() { disconnected = true; } }), false);
  assert.equal(disconnected, true);
  assert.equal((await db.user.findUniqueOrThrow({ where: { id: normalUser.id } })).status, 'ACTIVE');
});
