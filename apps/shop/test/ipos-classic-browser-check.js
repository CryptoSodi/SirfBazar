// Run after ipos-browser-fixture.js (all API requests must be mocked).
// playwright-cli run-code --filename apps/shop/test/ipos-classic-browser-check.js
async (page) => {
  if (!await page.evaluate(async () => { const r = await fetch('/api/__fixture/stats'); return r.ok && Number.isInteger((await r.json()).sales); })) throw Error('Mock fixture required');
  const state = () => page.evaluate(() => JSON.parse(localStorage.getItem('sb.ipos.v1:ipos-test-shop:ipos-test-cashier')));
  const check = (ok, message) => { if (!ok) throw Error(message); console.log(`PASS ${message}`); };
  const wait = (predicate) => page.waitForFunction(predicate);
  const nav = (label) => page.getByRole('navigation', { name: 'iPOS workspace' }).getByRole('button', { name: label, exact: true });
  const profile = async (value) => {
    await nav('POS settings').click();
    await page.getByRole('button', { name: 'Keyboard commands', exact: true }).click();
    await page.getByRole('combobox', { name: /^Keyboard profile/ }).selectOption(value);
    await page.getByRole('button', { name: /^Save preferences/ }).click();
    await nav('Register').click();
  };
  await nav('Register').click();
  if (!(await state())?.draft.lines.length) await page.getByRole('button', { name: /^Fresh milk 1 litre/ }).click();
  if ((await state()).settings.appearance !== 'classic') await page.getByRole('button', { name: /^Classic appearance/ }).click();
  await profile('website');
  await page.keyboard.press('F2');
  check(await page.getByRole('textbox', { name: /^Find a product/ }).evaluate(el => el === document.activeElement), 'website F2 focuses description search');
  await page.keyboard.press('F4');
  check(await page.getByRole('textbox', { name: /^Barcode \/ shop SKU/ }).evaluate(el => el === document.activeElement), 'website F4 focuses scan');
  await profile('website-code-first');
  await page.keyboard.press('F2');
  check(await page.getByRole('textbox', { name: /^Barcode \/ shop SKU/ }).evaluate(el => el === document.activeElement), 'code-first F2 focuses scan');
  await page.keyboard.press('F4');
  check(await page.getByRole('textbox', { name: /^Find a product/ }).evaluate(el => el === document.activeElement), 'code-first F4 focuses description search');
  await profile('website');
  await page.keyboard.press('F7');
  await page.getByRole('textbox', { name: 'Whole-unit quantity' }).fill('3');
  await page.getByRole('button', { name: 'Apply quantity', exact: true }).click();
  await page.getByRole('textbox', { name: /^Barcode \/ shop SKU/ }).fill('0123456');
  await page.keyboard.press('Enter');
  await wait(() => JSON.parse(localStorage.getItem('sb.ipos.v1:ipos-test-shop:ipos-test-cashier')).draft.lines.some(l => l.product.merchantProductId === 'eggs' && l.quantity === 3));
  check(true, 'F7 quantity applies to the next scan');
  await page.getByRole('textbox', { name: /^Barcode \/ shop SKU/ }).fill('0123456'); await page.keyboard.press('Enter');
  await wait(() => JSON.parse(localStorage.getItem('sb.ipos.v1:ipos-test-shop:ipos-test-cashier')).draft.lines.some(l => l.product.merchantProductId === 'eggs' && l.quantity === 4));
  check(true, 'following scan returns to one unit');
  await page.keyboard.press('F11');
  await page.getByRole('textbox', { name: 'Whole-unit quantity' }).fill('999');
  await page.getByRole('button', { name: 'Apply quantity', exact: true }).click();
  check((await page.getByRole('dialog').innerText()).includes('Only 24 units'), 'quantity rejects insufficient stock');
  await page.getByRole('textbox', { name: 'Whole-unit quantity' }).fill('2');
  await page.getByRole('button', { name: 'Apply quantity', exact: true }).click();
  check((await state()).draft.lines.find(l => l.product.merchantProductId === 'eggs').quantity === 2, 'website F11 changes quantity without resetting bill');
  await page.keyboard.press('F5');
  const beforeVoid = JSON.stringify((await state()).draft);
  await page.getByRole('textbox', { name: /^Barcode \/ shop SKU/ }).fill('0012345'); await page.keyboard.press('Enter');
  await page.getByRole('button', { name: 'Keep unit', exact: true }).click();
  check(JSON.stringify((await state()).draft) === beforeVoid, 'void cancellation retains bill');
  await page.getByRole('textbox', { name: /^Barcode \/ shop SKU/ }).fill('0012345'); await page.keyboard.press('Enter');
  await page.getByRole('button', { name: 'Void one unit', exact: true }).click();
  check(!(await state()).draft.lines.some(l => l.product.merchantProductId === 'milk'), 'F5 void confirms removal of one unpaid unit');
  await page.keyboard.press('F5');
  const draft = JSON.stringify((await state()).draft);
  await page.getByRole('button', { name: /^Classic appearance/ }).click();
  check(JSON.stringify((await state()).draft) === draft, 'appearance toggle preserves bill identity and content');
  await page.getByRole('button', { name: /^Classic appearance/ }).click();
  await page.reload();
  await page.getByRole('button', { name: 'Classic appearance On', exact: true }).waitFor();
  check((await state()).settings.shortcutProfile === 'website' && JSON.stringify((await state()).draft) === draft, 'appearance, profile and bill persist after reload');
  await profile('video');
  await page.keyboard.press('F11');
  check(await page.getByRole('dialog', { name: 'Discard this unpaid bill?' }).isVisible(), 'video F11 opens Reset confirmation');
  await page.keyboard.press('F12');
  check(await page.getByRole('dialog', { name: 'Discard this unpaid bill?' }).isVisible(), 'shortcut cannot replace an open confirmation');
  await page.getByRole('button', { name: 'Keep bill', exact: true }).click();
  await page.keyboard.press('F12');
  check(await page.getByRole('dialog', { name: 'Leave the counter?' }).isVisible(), 'video F12 opens Exit confirmation');
  await page.getByRole('button', { name: 'Stay at counter', exact: true }).click();
  check(JSON.stringify((await state()).draft) === draft, 'Reset and Exit cancellation preserve draft');
  await profile('sirfbazar');
  await page.keyboard.press('F6');
  check((await state()).held.length === 1 && !(await state()).draft.lines.length, 'SirfBazar F6 holds bill');
  await page.keyboard.press('F7'); await page.getByRole('button', { name: 'Recall bill', exact: true }).click();
  check((await state()).held.length === 0 && JSON.stringify((await state()).draft) === draft, 'F7 recall restores same bill');
  await page.keyboard.press('F10');
  await page.getByRole('textbox', { name: 'Cash received', exact: true }).fill('500');
  await page.keyboard.press('F5');
  check(await page.getByRole('dialog', { name: 'Cash payment' }).isVisible(), 'keyboard does not operate through payment');
  await page.getByRole('button', { name: 'Complete cash sale', exact: true }).click();
  await page.getByRole('dialog', { name: 'Saved sale receipt' }).waitFor();
  check((await page.getByRole('dialog').innerText()).includes('Rs 20.00'), 'mock cash sale saves correct change');
  await page.getByRole('button', { name: 'Back to counter', exact: true }).click();
  await nav('POS settings').click(); await page.getByRole('button', { name: 'Keyboard commands', exact: true }).click();
  await page.getByRole('combobox', { name: 'Shortcut for Reset bill', exact: true }).selectOption('F2');
  await page.getByRole('button', { name: /^Save preferences/ }).click();
  check((await state()).settings.shortcutProfile === 'sirfbazar', 'duplicate shortcut cannot be saved');
  await page.getByRole('combobox', { name: 'Shortcut for Reset bill', exact: true }).selectOption('Alt+Z');
  await page.getByRole('button', { name: /^Save preferences/ }).click(); await nav('Register').click();
  check((await state()).settings.shortcutProfile === 'custom', 'custom mapping saves after resolving duplicate');
  await page.getByRole('button', { name: /^Fresh milk 1 litre/ }).click();
  await page.getByRole('textbox', { name: /^Find a product/ }).focus(); await page.keyboard.press('Alt+z');
  check(await page.getByRole('dialog').count() === 0, 'Alt-letter shortcut ignores text inputs');
  await nav('Register').focus(); await page.keyboard.press('Alt+z');
  check(await page.getByRole('dialog', { name: 'Discard this unpaid bill?' }).isVisible(), 'custom Alt+Z works outside text inputs');
  await page.getByRole('button', { name: 'Keep bill', exact: true }).click();
  await page.screenshot({ path: 'output/playwright/ipos-classic-populated.png', fullPage: true });
  console.log('All Classic browser checks passed with mocked API data only.');
  return { passed: true, profiles: ['website', 'website-code-first', 'video', 'sirfbazar', 'custom'], data: 'mocked only' };
}
